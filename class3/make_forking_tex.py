"""'Garden of forking paths' figure for the big-picture section: 16 defensible analyses
of the thin vs medium comparison on the teaching subsample (four binary choices), drawn
as a tree whose leaves are the p-values. Writes tex/forking_paths.tex, compiles it and
exports img/forking_paths.png (transparent)."""
import itertools, subprocess
from pathlib import Path
import pandas as pd
from scipy import stats

HERE = Path(__file__).resolve().parent
TEX, IMG, NAME = HERE / "tex", HERE / "img", "forking_paths"
d = pd.read_csv(HERE.parent / "Data" / "arc_magmas_crust_sample.csv")
tm = d[d.crust_class.isin(["thin", "medium"])]

LEVELS = [("groups", ["cut at 30 km", "cut at 35 km"]),
          ("test", ["Welch", "Wilcoxon"]),
          ("alternative", ["two-sided", "one-sided"]),
          ("outliers", ["keep all", "drop $>$ 70"])]

def pval(cut, test, alt, outl):
    if cut == 0:
        x, y = tm.loc[tm.crust_class == "thin", "sio2"], tm.loc[tm.crust_class == "medium", "sio2"]
    else:
        x, y = tm.loc[tm.crust_km < 35, "sio2"], tm.loc[tm.crust_km >= 35, "sio2"]
    if outl == 1:
        x, y = x[x <= 70], y[y <= 70]
    alternative = "two-sided" if alt == 0 else "less"
    if test == 0:
        return stats.ttest_ind(x, y, alternative=alternative, equal_var=False).pvalue
    return stats.mannwhitneyu(x, y, alternative=alternative).pvalue

leaves = list(itertools.product((0, 1), repeat=4))
ps = [pval(*c) for c in leaves]
for c, p in zip(leaves, ps):
    print(" / ".join(LEVELS[k][1][v] for k, v in enumerate(c)), f"p = {p:.4f}", "*" if p < .05 else "")
print(f"significant: {sum(p < .05 for p in ps)}/16, range {min(ps):.4f}-{max(ps):.4f}")

# ---- drawing: root on the left, 16 leaves on the right. Nodes are boxes; branches run
# from the right edge of a box to the left edge of its children as smooth curves.
X = [0.0, 3.3, 6.5, 9.7, 12.9]             # x of the root and of the 4 levels (box centres)
DY = 0.62                                  # leaf spacing
n = len(leaves)
def y_of(level, index):                    # centre of node `index` at `level` (level 0 = root)
    span = n // (2 ** level)
    return -((index + 0.5) * span - 0.5) * DY
o = []
ytop = y_of(4, 0) + 0.75                   # header baseline, just above the first leaf
for k, (name, _) in enumerate(LEVELS):
    o.append(r"\node[txt, font=\small\bfseries, anchor=base] at (%.2f,%.2f) {%s};" % (X[k + 1], ytop, name))
o.append(r"\node[txt, font=\small\bfseries, anchor=base west] at (%.2f,%.2f) {p-value};" % (X[4] + 1.15, ytop))
o.append(r"\node[rootbox] (n0_0) at (%.2f,%.2f) {thin vs\\medium crust};" % (X[0], y_of(0, 0)))
for level in range(1, 5):
    for i in range(2 ** level):
        label = LEVELS[level - 1][1][i % 2]
        style = "leafbox" if level == 4 else "box"
        o.append(r"\node[%s] (n%d_%d) at (%.2f,%.2f) {%s};" % (style, level, i, X[level], y_of(level, i), label))
        o.append(r"\draw[branch] (n%d_%d.east) .. controls +(0.9,0) and +(-0.9,0) .. (n%d_%d.west);" % (level - 1, i // 2, level, i))
        if level == 4:
            p = ps[i]
            col = "cpink" if p < 0.05 else "cgrey"
            o.append(r"\node[%s, font=\small\bfseries, anchor=west] at (%.2f,%.2f) {%s};" % (col, X[4] + 1.15, y_of(4, i), ("%.3f" % p) if p >= 0.0005 else "$<$0.001"))
o.append(r"\node[txt, font=\small, anchor=west] at (%.2f,%.2f) {{\color{cpink}\textbf{pink}}: $p < 5\%%$ \quad {\color{cgrey}\textbf{grey}}: $p \geq 5\%%$};" % (X[1] - 0.6, y_of(4, 15) - 0.85))
tex = r"""% GENERATED by make_forking_tex.py -- edit the script, not this file.
\documentclass[tikz,border=4pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\definecolor{cpurple}{HTML}{6A5ACD}
\definecolor{cpink}{HTML}{EB078E}
\definecolor{cgrey}{RGB}{150,150,150}
\definecolor{cline}{RGB}{160,160,172}
\definecolor{cleaf}{RGB}{245,245,247}
\definecolor{txt}{RGB}{85,85,85}
\begin{document}
\begin{tikzpicture}[x=1cm,y=1cm,line cap=round,line join=round,
  box/.style={draw=cline, fill=white, rounded corners=3pt, line width=0.6pt, inner xsep=5pt, inner ysep=2.5pt, font=\small, text=txt},
  leafbox/.style={box, fill=cleaf},
  rootbox/.style={box, draw=cpurple, line width=0.9pt, align=center, font=\small\bfseries, text=cpurple, inner ysep=4pt},
  branch/.style={cline, line width=0.8pt}]
""" + "\n".join(o) + "\n\\end{tikzpicture}\n\\end{document}\n"
TEX.mkdir(exist_ok=True)
(TEX / f"{NAME}.tex").write_text(tex)
subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", f"{NAME}.tex"], cwd=TEX, check=True, stdout=subprocess.DEVNULL)
subprocess.run(["pdftocairo", "-png", "-transp", "-singlefile", "-scale-to-x", "2200", "-scale-to-y", "-1",
                str(TEX / f"{NAME}.pdf"), str(IMG / NAME)], check=True)
for ext in ("aux", "log", "pdf"):
    (TEX / f"{NAME}.{ext}").unlink(missing_ok=True)
print(f"Saved img/{NAME}.png")
