"""Fig. 2 of Farner & Lee (2017, EPSL 470) redrawn from their supplementary Table 3
(sample-level data, Data/1-s2.0-S0012821X17302108-mmc3.xlsx): SiO2 histograms per
elevation bin with mean and median. Writes tex/sio2_elevation_hist.tex, compiles it and
exports img/sio2_elevation_hist.png (transparent).
"""
import subprocess
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
XLSX = HERE.parent / "Data" / "1-s2.0-S0012821X17302108-mmc3.xlsx"
TEX = HERE / "tex"
IMG = HERE / "img"
NAME = "sio2_elevation_hist"

raw = pd.read_excel(XLSX, sheet_name="Table 3-10 km^2 data", header=1)
raw = raw.dropna(subset=["SiO2 (wt%)", "Elevation (m)"])
EDGES = [-500, 500, 1500, 2500, 3500, 4500, 5500]
raw["bin"] = pd.cut(raw["Elevation (m)"], EDGES, right=False, labels=False)

XMIN, XMAX, DX = 40, 85, 1          # histogram range and bin width (wt.%)
W, HP = 4.2, 2.1                    # panel width / height (cm)
COLX = [0.0, 5.7]                   # left / right column
ROWY = [0.0, 2.85, 5.7]             # bottom / middle / top row
YMAX = 11.0                         # % of samples (common scale)
edges = np.arange(XMIN, XMAX + DX, DX)

def xs(v):
    return (v - XMIN) / (XMAX - XMIN) * W

def ys(p):
    return p / YMAX * HP

o = []
letters = "ABCDEF"
for k in range(6):
    sub = raw.loc[raw["bin"] == k]
    n_tot = len(sub)
    n_unit = sub.groupby(["Latitude", "Longitude"]).ngroups
    cnt, _ = np.histogram(sub["SiO2 (wt%)"], bins=edges)
    pct = 100 * cnt / n_tot
    mean, med = sub["SiO2 (wt%)"].mean(), sub["SiO2 (wt%)"].median()
    print(f"{letters[k]} {EDGES[k]:>5}-{EDGES[k+1]:<5} m  cells={n_unit:5d} samples={n_tot:6d}  mean={mean:5.1f} median={med:5.1f} max%={pct.max():.1f}")
    x0, y0 = COLX[k // 3], ROWY[k % 3]
    o.append(r"\begin{scope}[shift={(%.2f,%.2f)}]" % (x0, y0))
    for a, p in zip(edges[:-1], pct):
        if p > 0:
            o.append(r"\fill[cbar] (%.3f,0) rectangle (%.3f,%.3f);" % (xs(a) + 0.01, xs(a + DX) - 0.01, ys(p)))
    o.append(r"\draw[txt, line width=0.9pt] (%.3f,0) -- (%.3f,%.3f);" % (xs(mean), xs(mean), HP * 0.95))
    o.append(r"\draw[cpink, line width=0.9pt, dash pattern=on 2.2pt off 1.6pt] (%.3f,0) -- (%.3f,%.3f);" % (xs(med), xs(med), HP * 0.95))
    # axes and ticks
    o.append(r"\draw[txt, line width=0.5pt] (0,%.2f) -- (0,0) -- (%.2f,0);" % (HP, W))
    for v in range(XMIN, XMAX + 1, 10):
        o.append(r"\draw[txt, line width=0.5pt] (%.3f,0) -- (%.3f,-0.07);" % (xs(v), xs(v)))
        if k % 3 == 0:
            o.append(r"\node[txt, font=\scriptsize, anchor=north] at (%.3f,-0.1) {%d};" % (xs(v), v))
    for p in (0, 5, 10):
        o.append(r"\draw[txt, line width=0.5pt] (0,%.3f) -- (-0.07,%.3f);" % (ys(p), ys(p)))
        o.append(r"\node[txt, font=\scriptsize, anchor=east] at (-0.1,%.3f) {%d};" % (ys(p), p))
    lo, hi = EDGES[k], EDGES[k + 1]
    lab = (r"$-500$ to $500$ m" if lo < 0 else r"$%d$ to $%d$ m" % (lo, hi))
    o.append(r"\node[txt, font=\scriptsize, anchor=south west] at (0,%.2f) {\textbf{%s}\; %s};" % (HP + 0.06, letters[k], lab))
    o.append(r"\node[txt, font=\scriptsize, anchor=south east] at (%.2f,%.2f) {$n = %s$};"
             % (W, HP + 0.06, f"{n_tot:,}".replace(",", "\\,")))
    o.append(r"\end{scope}")

# axis titles and legend
for x0 in COLX:
    o.append(r"\node[txt, font=\small] at (%.2f,-0.55) {SiO$_2$ (wt.\%%)};" % (x0 + W / 2))
o.append(r"\node[txt, font=\small, rotate=90] at (-0.62,%.2f) {\%% of samples};" % (ROWY[1] + HP / 2))
lx, ly = COLX[1] + W / 2 - 1.3, -1.05
o.append(r"\draw[txt, line width=0.9pt] (%.2f,%.2f) -- (%.2f,%.2f);" % (lx, ly, lx + 0.45, ly))
o.append(r"\node[txt, font=\scriptsize, anchor=west] at (%.2f,%.2f) {mean};" % (lx + 0.5, ly))
o.append(r"\draw[cpink, line width=0.9pt, dash pattern=on 2.2pt off 1.6pt] (%.2f,%.2f) -- (%.2f,%.2f);" % (lx + 1.5, ly, lx + 1.95, ly))
o.append(r"\node[txt, font=\scriptsize, anchor=west] at (%.2f,%.2f) {median};" % (lx + 2.0, ly))
AX = -1.15                           # elevation arrow: left of the tick labels and the axis title
o.append(r"\node[txt, font=\scriptsize, anchor=south] at (%.2f,%.2f) {elevation};" % (AX, ROWY[2] + HP + 0.62))
o.append(r"\draw[txt, line width=0.6pt, -{Stealth[length=4pt]}] (%.2f,%.2f) -- (%.2f,%.2f);" % (AX, ROWY[0] + 0.2, AX, ROWY[2] + HP + 0.55))

tex = r"""% GENERATED by make_fig2_tex.py -- edit the script, not this file.
\documentclass[tikz,border=4pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\usetikzlibrary{arrows.meta}
\definecolor{cbar}{RGB}{236,112,52}
\definecolor{cpink}{HTML}{EB078E}
\definecolor{txt}{RGB}{85,85,85}
\begin{document}
\begin{tikzpicture}[x=1cm,y=1cm,line cap=round,line join=round]
""" + "\n".join(o) + "\n\\end{tikzpicture}\n\\end{document}\n"
TEX.mkdir(exist_ok=True)
(TEX / f"{NAME}.tex").write_text(tex)
subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", f"{NAME}.tex"], cwd=TEX, check=True, stdout=subprocess.DEVNULL)
subprocess.run(["pdftocairo", "-png", "-transp", "-singlefile", "-scale-to-x", "2000", "-scale-to-y", "-1",
                str(TEX / f"{NAME}.pdf"), str(IMG / NAME)], check=True)
for ext in ("aux", "log", "pdf"):
    (TEX / f"{NAME}.{ext}").unlink(missing_ok=True)
print(f"Saved img/{NAME}.png")
