"""Derive the PDF/offline deck from the live source; compute real summary output."""
from pathlib import Path
from contextlib import redirect_stdout
import io
import os
import re
import sys
ROOT=Path(__file__).resolve().parent
source=ROOT.parent/'class_4_slides.qmd'
target=source.with_name('class_4_slides_static.qmd')
text=source.read_text()
header,body=text[4:].split('\n---\n',1)
header=header.replace('  live-revealjs:','  revealjs:',1).replace('    embed-resources: false','    embed-resources: true',1)
header=re.sub(r'\npyodide:\n  packages:.*\n  resources:.*\n','\n',header,count=1)
header += '\ncode-line-numbers: false'
header=header.replace('\ninclude-after-body: original_style/summary_note.js','',1)
header=re.sub(r'\nojs-engine: true\nfilters:.*\n','\n',header,count=1)
def convert(match):
    code=match[1]
    rendered='```python\n'+code+'```'
    summary_call=re.search(r'display\((simple|multiple|quadratic)\.summary\(slim=True\)\)',code)
    if summary_call is None:
        return rendered
    model_name=summary_call[1]
    # Execute exactly the student code in a fresh namespace; only training is fitted.
    cwd=Path.cwd()
    try:
        os.chdir(ROOT.parent)
        sys.path.insert(0,str(ROOT.parent))
        namespace={}
        with redirect_stdout(io.StringIO()):
            exec(code,namespace)
        summary=namespace[model_name].summary(slim=True).as_html()
        summary=summary.replace(
            'Standard Errors assume that the covariance matrix of the errors is correctly specified.',
            'The coefficient standard errors assume constant error variance and uncorrelated errors across observations.')
    finally:
        os.chdir(cwd)
        sys.path.pop(0)
    (ROOT/f'{model_name}_ols_summary.html').write_text('<!-- Generated from the frozen CPX training fit by make_static.py. -->\n'+summary+'\n')
    return ('::::: {.summary-panels}\n:::: {.summary-code}\n'+rendered+'\n::::\n'
            ':::: {.summary-output}\n```{=html}\n'+summary+'\n```\n::::\n:::::')
body=re.sub(r'```\{pyodide\}\n(.*?)```',convert,body,flags=re.S)
assert '{pyodide}' not in body
assert 'live-revealjs' not in header and '\npyodide:' not in header
target.write_text('---\n# Generated by original_style/make_static.py; edit the live QMD.\n'+header+'\n---\n'+body)
print('Generated',target)
