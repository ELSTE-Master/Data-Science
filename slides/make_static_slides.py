"""Derive the static, self-contained Class 3 deck from the live one.

class_3_slides.qmd is the source of truth (live-revealjs: students run the
Python cells in their browser on the course website). This script writes
class_3_slides_static.qmd, the same deck rendered with clean-revealjs and
embed-resources, where the cells are executed at render time instead. The
static HTML is the downloadable/offline version and the source of the PDF.

Run after editing the live deck:  python slides/make_static_slides.py
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "class_3_slides.qmd"
DST = HERE / "class_3_slides_static.qmd"
URL = "https://raw.githubusercontent.com/ELSTE-Master/Data-Science/main/Data/arc_magmas_crust_sample.csv"
LOCAL = "../Data/arc_magmas_crust_sample.csv"

s = SRC.read_text(encoding="utf-8")

# ---- header: live-revealjs + pyodide  ->  clean-revealjs, self-contained ----
a = s.index("format:\n  live-revealjs:")
b = s.index("css: [", a)
s = s[:a] + '''format:
  clean-revealjs:
    chalkboard: false
    embed-resources: true
    self-contained: true
    self-contained-math: true
    mathjax: "https://cdn.jsdelivr.net/npm/mathjax@3/es5/tex-mml-chtml.js"
    slide-number: true
''' + s[b:]

# ---- cells ----
def convert(match):
    raw = match.group(1)
    lines = raw.rstrip("\n").split("\n")
    opts = {}
    while lines and lines[0].startswith("#|"):
        k, _, v = lines.pop(0)[2:].partition(":")
        opts[k.strip()] = v.strip()
    body = "\n".join(lines).strip("\n")
    if all(l.strip() in ("", "# Your code here") for l in lines):
        return ""                                   # students' empty cell: nothing to show statically
    if opts.get("include") == "false":              # hidden setup cell of the live deck
        return "```{python}\n#| include: false\n" + body.replace(URL, LOCAL) + "\n```\n"
    if URL in body:
        # Show the cell as the students see it (GitHub URL, not executed), then run the
        # same code on the local copy without echo so its output appears right below.
        out = "```{python}\n#| echo: true\n#| eval: false\n" + body + "\n```\n\n"
        out += "```{python}\n#| echo: false\n" + body.replace(URL, LOCAL) + "\n```\n"
        return out
    return "```{python}\n#| echo: true\n" + body + "\n```\n"

s = re.sub(r"```\{pyodide\}\n(.*?)```\n", convert, s, flags=re.S)
assert "{pyodide}" not in s

# ---- banner inside the front matter (a YAML comment adds no slide) ----
assert s.startswith("---\n")
s = "---\n# GENERATED by make_static_slides.py from class_3_slides.qmd -- edit the live deck, not this file.\n" + s[4:]
DST.write_text(s, encoding="utf-8")
print("wrote", DST.name, "|", s.count("```{python}"), "python chunks")
